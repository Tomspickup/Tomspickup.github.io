const usageTranslationKeys = {
  daily: "usageDaily",
  cargo: "usageCargo",
  mixed: "usageMixed",
  travel: "usageTravel"
};

const contactTranslationKeys = {
  line: "contactOptionLine",
  phone: "contactOptionPhone",
  facebook: "contactOptionFacebook"
};

const page = document.body.dataset.page || "home";
const langButtons = document.querySelectorAll(".lang-switch__button");
const inquiryStorageKey = "pickup-inquiry-draft";
let currentLanguage = "th";

function getDictionary(lang) {
  return translations[lang] || translations.th;
}

function setTextContent(selector, value) {
  const element = document.querySelector(selector);
  if (element) {
    element.textContent = value;
  }
}

function setMetaContent(element, value) {
  if (!element || !value) {
    return;
  }

  if (element.tagName === "TITLE") {
    element.textContent = value;
    document.title = value;
    return;
  }

  element.setAttribute("content", value);
}

function applyTranslations(lang) {
  currentLanguage = translations[lang] ? lang : "th";
  const dictionary = getDictionary(currentLanguage);

  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n-meta]").forEach((element) => {
    const key = element.dataset.i18nMeta;
    setMetaContent(element, dictionary[key]);
  });

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (dictionary[key]) {
      element.innerHTML = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (dictionary[key]) {
      element.alt = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (dictionary[key]) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      element.setAttribute("placeholder", dictionary[key]);
    }
  });

  langButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === currentLanguage);
  });

  if (page === "thank-you") {
    renderThankYouPage();
  }
}

function setLanguage(lang) {
  const nextLanguage = translations[lang] ? lang : "th";
  localStorage.setItem("preferred-language", nextLanguage);
  applyTranslations(nextLanguage);
}

function initializeLanguageControls() {
  const preferredLanguage = localStorage.getItem("preferred-language") || "th";
  applyTranslations(preferredLanguage);

  langButtons.forEach((button) => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.lang);
    });
  });
}

function getFormValue(formData, key) {
  return String(formData.get(key) || "").trim();
}

function getTranslatedChoice(dictionary, translationMap, value) {
  const key = translationMap[value];
  return key ? dictionary[key] : value;
}

function buildInquiryMessage(data, dictionary) {
  if (!data || !data.truckDetails) {
    return dictionary.defaultLineMessage;
  }

  const lines = [
    dictionary.lineMessageIntro,
    `${dictionary.lineMessageName}: ${data.customerName || dictionary.summaryFallback}`,
    `${dictionary.lineMessageTruck}: ${data.truckDetails || dictionary.summaryFallback}`,
    `${dictionary.lineMessageUsage}: ${getTranslatedChoice(dictionary, usageTranslationKeys, data.usageType) || dictionary.summaryFallback}`,
    `${dictionary.lineMessageSymptoms}: ${data.symptoms || dictionary.summaryFallback}`,
    `${dictionary.lineMessageProvince}: ${data.province || dictionary.summaryFallback}`,
    `${dictionary.lineMessageContact}: ${getTranslatedChoice(dictionary, contactTranslationKeys, data.preferredContact) || dictionary.summaryFallback}`,
    `${dictionary.lineMessageNote}: ${data.extraNote || dictionary.summaryFallback}`,
    dictionary.lineMessageClosing
  ];

  return lines.join("\n");
}

function initializeInquiryForm() {
  const inquiryForm = document.getElementById("inquiry-form");
  if (!inquiryForm) {
    return;
  }

  inquiryForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const formData = new FormData(inquiryForm);
    const draft = {
      customerName: getFormValue(formData, "customerName"),
      truckDetails: getFormValue(formData, "truckDetails"),
      usageType: getFormValue(formData, "usageType"),
      preferredContact: getFormValue(formData, "preferredContact"),
      symptoms: getFormValue(formData, "symptoms"),
      province: getFormValue(formData, "province"),
      extraNote: getFormValue(formData, "extraNote")
    };

    sessionStorage.setItem(inquiryStorageKey, JSON.stringify(draft));
    window.location.href = "thank-you.html";
  });
}

function getStoredInquiry() {
  try {
    const raw = sessionStorage.getItem(inquiryStorageKey);
    return raw ? JSON.parse(raw) : null;
  } catch {
    return null;
  }
}

function renderThankYouPage() {
  const dictionary = getDictionary(currentLanguage);
  const draft = getStoredInquiry();
  const summary = draft || {};
  const fallback = dictionary.summaryFallback;

  setTextContent("#summary-name", summary.customerName || fallback);
  setTextContent("#summary-truck", summary.truckDetails || fallback);
  setTextContent("#summary-usage", summary.usageType ? getTranslatedChoice(dictionary, usageTranslationKeys, summary.usageType) : fallback);
  setTextContent("#summary-symptoms", summary.symptoms || fallback);
  setTextContent("#summary-province", summary.province || fallback);
  setTextContent("#summary-contact", summary.preferredContact ? getTranslatedChoice(dictionary, contactTranslationKeys, summary.preferredContact) : fallback);
  setTextContent("#summary-note", summary.extraNote || fallback);

  const lineMessage = buildInquiryMessage(draft, dictionary);
  const lineMessageField = document.getElementById("line-message");

  if (lineMessageField) {
    lineMessageField.value = lineMessage;
  }
}

function initializeThankYouActions() {
  const copyButton = document.getElementById("copy-message-button");
  const lineMessageField = document.getElementById("line-message");
  const feedback = document.getElementById("copy-feedback");

  if (!copyButton || !lineMessageField || !feedback) {
    return;
  }

  copyButton.addEventListener("click", async () => {
    const dictionary = getDictionary(currentLanguage);

    try {
      await navigator.clipboard.writeText(lineMessageField.value);
      feedback.textContent = dictionary.copySuccess;
    } catch {
      feedback.textContent = dictionary.copyFailed;
    }
  });
}

initializeLanguageControls();
initializeInquiryForm();
initializeThankYouActions();
